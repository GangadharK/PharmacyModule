package com.potlatech.pharmacy.entity;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.NoArgsConstructor;
import lombok.ToString;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

/**
 * A pharmacy staff account.
 *
 * <p>Schema: {@code MDD.md} §3.1. See {@code specs/02-auth-rbac/02a} for the
 * sub-spec this implements.
 *
 * <p><strong>Never returned from a controller.</strong> {@code AGENTS.md} rule 5
 * — a JPA entity escaping the service layer leaks the password hash. Responses
 * are {@code UserResponse} DTOs built by the service, which simply do not have
 * a field for the hash.
 *
 * <p><strong>No {@code indexes} in {@code @Table}.</strong> {@code ddl-auto} is
 * {@code validate}, so an index declared here but absent from the migration is a
 * discrepancy; and because V1 is already applied to both engines, a migration
 * cannot be edited to add it. The only index on this table is
 * {@code uk_users_username}, which serves the one hot query (login by username).
 * Listing users ordered by {@code full_name} is a full scan over a table measured
 * in dozens of rows, which does not justify an index or a V2.
 *
 * <p><strong>The id carries no converter and no columnDefinition.</strong> Hibernate
 * maps {@link UUID} to PostgreSQL {@code uuid} natively and round-trips it
 * correctly, so the mapping needs no help. An {@code AttributeConverter} was
 * written and then deleted: it existed only to bridge {@link UUID} to MySQL's
 * {@code BINARY(16)}, and with MySQL removed (decision 22) it had no consumer.
 * A {@code columnDefinition = "..."} is worse than useless here, because it
 * hardcodes DDL into an entity that {@code ddl-auto: validate} checks against the
 * live schema.
 *
 * <p>IDs are generated by the application, never by {@code @GeneratedValue}:
 * {@code AGENTS.md} forbids {@code GenerationType.UUID} so a ledger row can
 * reference a batch written earlier in the same transaction.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Entity
@Table(name = "users")
public class User {

    @Id
    private UUID id;

    @Column(name = "username", nullable = false, length = 100)
    private String username;

    @ToString.Exclude
    @EqualsAndHashCode.Exclude
    @JsonIgnore
    @Column(name = "password_hash", nullable = false, length = 255)
    private String passwordHash;

    @Column(name = "full_name", nullable = false, length = 255)
    private String fullName;

    @Enumerated(EnumType.STRING)
    @Column(name = "role", nullable = false, length = 30)
    private Role role;

    @Builder.Default
    @Column(name = "is_active", nullable = false)
    private Boolean isActive = true;

    @Builder.Default
    @Column(name = "created_at", nullable = false)
    private LocalDateTime createdAt = LocalDateTime.now();

     @Column(name = "last_login_at")
    private LocalDateTime lastLoginAt;


    public enum Role {
        SUPER_ADMIN,
        PHARMACY_MANAGER,
        PHARMACIST,
        CASHIER;


        public List<GrantedAuthority> authorities() {
            return java.util.Arrays.stream(values())
                    .filter(this::atLeast)
                    .map(r -> (GrantedAuthority) new SimpleGrantedAuthority("ROLE_" + r.name()))
                    .toList();
        }

        public boolean atLeast(Role other) {
            return this.ordinal() <= other.ordinal();
        }
    }
}
